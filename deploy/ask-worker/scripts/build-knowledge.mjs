// Builds src/knowledge.js from the project README and basics.md, so the assistant answers from the same
// text the repository shows. Run after the README changes: npm run knowledge
import { readFileSync, writeFileSync } from 'node:fs';

const here = new URL('..', import.meta.url);
let readme = readFileSync(new URL('../../README.md', here), 'utf8');

// Keep the substance; drop what only matters to someone running the code.
const drop = ['## Run it yourself', '## Project layout'];
for (const heading of drop) {
  const start = readme.indexOf(heading);
  if (start === -1) continue;
  const next = readme.indexOf('\n## ', start + heading.length);
  readme = readme.slice(0, start) + (next === -1 ? '' : readme.slice(next + 1));
}
readme = readme
  .replace(/<img[^>]*>\s*/g, '')
  .replace(/```mermaid[\s\S]*?```\s*/g, '')
  .replace(/\n{3,}/g, '\n\n')
  .trim();

const basics = readFileSync(new URL('basics.md', here), 'utf8').trim();
const pages = `## Dashboard pages

- Tomorrow (home page): tomorrow's 24 hourly forecasts with P10 to P90 ranges, the cheapest and priciest windows, and a summary.
- Track record: live forecasts scored against published prices, kept apart from the backtest, plus simple baselines.
- Model: how the model works, backtest breakdown by hour and month, and feature importance.
- EV charging: finds the cheapest hours to charge an electric car within a plug-in window and estimates the saving.
- About: the project, data sources and limitations.

depower was built by Abdul Habeeb, a Data Science and AI master's student in Saarbrücken (abdulhabeeb.com).`;

const doc = `${readme}\n\n${pages}\n\n${basics}\n`;
writeFileSync(new URL('src/knowledge.js', here),
  `// Generated by scripts/build-knowledge.mjs from the README and basics.md. Do not edit.\nexport default ${JSON.stringify(doc)};\n`);
console.log(`knowledge: ${doc.length.toLocaleString()} characters (~${Math.round(doc.length / 4).toLocaleString()} tokens)`);
